    private static String dec(byte[] data) {
        byte[] out = new byte[data.length];
        for (int i = 0; i < data.length; i++) {
            int k = (0x4B + (i * 7 + 13)) & 0xFF;
            out[i] = (byte) ((data[i] & 0xFF) ^ k);
        }
        return new String(out, StandardCharsets.UTF_8);
    }

